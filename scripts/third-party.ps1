# Generates the list of third-party components shipped in the APK, with
# their licenses: legal/THIRD_PARTY.md and the copy shown in the app
# (android/app/src/main/assets/third_party.md). Run before each release.
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
. (Join-Path $PSScriptRoot 'env.ps1')

$lines = New-Object System.Collections.Generic.List[string]
$lines.Add('# Third-party components')
$lines.Add('')
$lines.Add('Coffer is free software under the GNU General Public License v3.0 or later. It includes the components below, each under its own license. Generated by `scripts/third-party.ps1`.')
$lines.Add('')
$lines.Add('## Rust crates (encryption engine)')
$lines.Add('')
$lines.Add('| Crate | Version | License |')
$lines.Add('|---|---|---|')
Push-Location (Join-Path $root 'core')
try {
    $tree = cargo tree -p coffer-ffi -e normal --target aarch64-linux-android --prefix none -f '{p}|{l}' 2>$null
    if ($LASTEXITCODE -ne 0) { throw 'cargo tree failed' }
} finally { Pop-Location }
$seen = @{}
foreach ($row in ($tree | Sort-Object -Unique)) {
    if ($row -notmatch '^(\S+) v(\S+)[^|]*\|(.*)$') { continue }
    $name = $Matches[1]; $ver = $Matches[2]; $lic = $Matches[3].Trim()
    if ($name -like 'coffer-*') { continue }
    $key = "$name@$ver"
    if ($seen[$key]) { continue }
    $seen[$key] = $true
    if ($name -eq 'fatfs') { $lic = "$lic (vendored with local patches, see core/third_party/fatfs)" }
    $lines.Add("| $name | $ver | $lic |")
}

$lines.Add('')
$lines.Add('## Android libraries')
$lines.Add('')
$lines.Add('| Library | Version | License |')
$lines.Add('|---|---|---|')
Push-Location (Join-Path $root 'android')
try {
    $deps = & .\gradlew.bat -q :app:dependencies --configuration releaseRuntimeClasspath 2>$null
    if ($LASTEXITCODE -ne 0) { throw 'gradle dependencies failed' }
} finally { Pop-Location }
# Licenses by group (all checked against the libraries' published POMs).
$licenses = [ordered]@{
    'androidx.'               = 'Apache-2.0'
    'com.google.dagger'       = 'Apache-2.0'
    'com.google.guava'        = 'Apache-2.0'
    'com.google.errorprone'   = 'Apache-2.0'
    'org.jetbrains.kotlinx'   = 'Apache-2.0'
    'org.jetbrains.kotlin'    = 'Apache-2.0'
    'org.jetbrains'           = 'Apache-2.0'
    'org.jspecify'            = 'Apache-2.0'
    'javax.inject'            = 'Apache-2.0'
    'jakarta.inject'          = 'Apache-2.0'
    'net.java.dev.jna'        = 'Apache-2.0 OR LGPL-2.1-or-later'
    'com.squareup.'           = 'Apache-2.0'
    'com.google.code.findbugs' = 'Apache-2.0'
}
$libs = @{}
foreach ($row in $deps) {
    if ($row -notmatch '([a-zA-Z0-9_.\-]+):([a-zA-Z0-9_.\-]+):([0-9][^ ]*?)(?: -> ([0-9][^ ]*))?(?: \(.\))?\s*$') { continue }
    $g = $Matches[1]; $a = $Matches[2]; $v = if ($Matches[4]) { $Matches[4] } else { $Matches[3] }
    $libs["${g}:${a}"] = $v
}
foreach ($k in ($libs.Keys | Sort-Object)) {
    $lic = 'see the library POM'
    foreach ($prefix in $licenses.Keys) { if ($k.StartsWith($prefix)) { $lic = $licenses[$prefix]; break } }
    $lines.Add("| $k | $($libs[$k]) | $lic |")
}

$text = ($lines -join "`n") + "`n"
$utf8 = New-Object Text.UTF8Encoding $false
[IO.File]::WriteAllText((Join-Path $root 'legal\THIRD_PARTY.md'), $text, $utf8)
$assets = Join-Path $root 'android\app\src\main\assets'
New-Item -ItemType Directory -Force $assets | Out-Null
[IO.File]::WriteAllText((Join-Path $assets 'third_party.md'), $text, $utf8)
Write-Host "Wrote $($seen.Count) crates and $($libs.Count) Android libraries."
