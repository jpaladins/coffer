/** Centered illustration, title, explanation and an optional action. */
@Composable
fun EmptyState(
    icon: ImageVector,
    title: String,
    body: String,
    modifier: Modifier = Modifier,
    action: (@Composable () -> Unit)? = null,
) {
    Column(
        modifier.fillMaxWidth().padding(horizontal = 32.dp, vertical = 24.dp),
        horizontalAlignment = Alignment.CenterHorizontally,
        verticalArrangement = Arrangement.Center,
    ) {
        HexBadge(icon, size = 96.dp)
        Spacer(Modifier.height(24.dp))
        Text(title, style = MaterialTheme.typography.headlineSmall, textAlign = TextAlign.Center)
        Spacer(Modifier.height(8.dp))
        Text(
            body,
            style = MaterialTheme.typography.bodyLarge,
            color = MaterialTheme.colorScheme.onSurfaceVariant,
            textAlign = TextAlign.Center,
        )
        if (action != null) {
            Spacer(Modifier.height(24.dp))
            action()
        }
    }
}

@Preview @Composable private fun EmptyLight() = CofferTheme(dark = false) {
    Surface { EmptyState(CofferIcons.FolderOpen, "No containers yet", "Add a VeraCrypt container file.") }
}
@Preview @Composable private fun EmptyDark() = CofferTheme(dark = true) {
    Surface { EmptyState(CofferIcons.FolderOpen, "No containers yet", "Add a VeraCrypt container file.") }
}
